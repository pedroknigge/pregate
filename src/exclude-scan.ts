// The shell around detectExclusions. It reads the tree and, on enable, writes the accepted
// globs through the same review as every other contract change. Audit only prints proposals.

const HEAVY = new Set(["node_modules", ".venv", "venv", "__pycache__", ".git", ".pregate"]);
const PROTECTED = new Set([".pregate", ".git", ".claude", ".codex", ".cursor", ".grok", ".gemini", ".agents", ".agent", ".opencode", ".local"]);
const HEADER_BYTES = 512;
const SMALL_DIR = 40;
const HEADER_BUDGET = 8000;
const IGNORE_BYTES = 256 * 1024;
const MARKERS = ["@generated", "code generated", "do not edit", "autogenerated", "auto-generated", "generated by", "this file is generated"];

interface Budget { left: number }
interface Acc { files: number; generatedHeaders: number; minified: number; protobuf: number; complete: boolean }
interface IgnoreFile { base: string; text: string }
interface ScanState { dirs: DirFacts[]; dirPaths: string[]; ignores: IgnoreFile[]; cargoDirs: string[]; budget: Budget }

export function scanExclusions(root: string, policy: { layerGlobs: string[]; excludeGlobs: string[] }): ExcludeCandidate[] {
  return detectExclusions(factsOf(root, policy));
}

// null: nothing new to accept, so enable keeps recording consent only. A note means a review is
// already pending and the contract was left alone. A code means this call finished enable.
export async function enableWithExclusions(root: string, yes: boolean): Promise<{ code: number; text: string } | { note: string } | null> {
  const preset = readPreset(root);
  if (preset === null) return { code: 1, text: `${PRESET} could not be read. Exclusions were not written and protection was not enabled.` };
  const policy = policyOf(preset);
  const found = scanExclusions(root, policy);
  if (found.length === 0) return null;
  return reviewExclusions(root, preset, found, yes);
}

function policyOf(preset: Preset): { layerGlobs: string[]; excludeGlobs: string[] } {
  return {
    layerGlobs: Object.values(preset.layers ?? {}).flatMap((layer) => layer.paths),
    excludeGlobs: preset.scope?.exclude ?? [],
  };
}

async function reviewExclusions(root: string, preset: Preset, found: ExcludeCandidate[], yes: boolean): Promise<{ code: number; text: string } | { note: string }> {
  const next = withExcludes(preset, found.map((item) => item.glob));
  const text = JSON.stringify(next, null, 2) + "\n";
  const pending = readProposal(root);
  if (pending !== null && !pending.writes.some((write) => write.after === text)) {
    return { note: `${proposalText(found)}\nA contract review is already pending, so these exclusions were not written. Finish it, then run pregate enable again.` };
  }
  const before = readText(join(root, PRESET));
  await grammars();
  const compiled = validateContract({ presetText: text, filesOf: sourcesOf(root, true), versions: VERSIONS, now: clock });
  if ("errors" in compiled) return { code: 1, text: [...compiled.errors, "Exclusions were not written and protection was not enabled."].join("\n") };
  const proposal = stageExclusions(root, before, text, compiled.text);
  const diff = reviewDiff(readText(join(root, LOCK)), compiled.lock, bundledBetween(before, text));
  const code = sha256(JSON.stringify(proposal)).slice(0, 12);
  // `enable --yes` is not `pregate approve`. CI alone must not accept the globs.
  if (!await approve([candidateBlock(found), ...diff.summary].join("\n"), diff.warning, yes, false)) {
    return { code: 1, text: `${candidateBlock(found)}\n${approvalRefusal({ roots: [root], command: `pregate approve ${code}` })}` };
  }
  const applied = await applyReviewedProposal(root, sha256(JSON.stringify(proposal)), { activate: true, commit: false });
  if (applied.code !== 0) return applied;
  return { code: 0, text: `${candidateBlock(found)}\n${applied.text}\nCommit ${PRESET} and ${LOCK} with the project.` };
}

function stageExclusions(root: string, before: string | null, text: string, lockText: string) {
  const baseline = sha256((before ?? "") + (readText(join(root, LOCK)) ?? ""));
  return proposeContract({ root, baseline, lockText, activate: true, writes: [{ path: join(root, PRESET), before, after: text }] }, true);
}

function withExcludes(preset: Preset, globs: string[]): Preset {
  const scope = preset.scope ?? {};
  const have = scope.exclude ?? [];
  const extra = globs.filter((glob) => !have.includes(glob));
  return { ...preset, scope: { ...scope, include: scope.include ?? ["**"], exclude: [...have, ...extra] } };
}

function readPreset(root: string): Preset | null {
  try {
    const preset = JSON.parse(readFileSync(join(root, PRESET), "utf8")) as Preset;
    return preset !== null && typeof preset === "object" ? preset : null;
  } catch {
    return null;
  }
}

function factsOf(root: string, policy: { layerGlobs: string[]; excludeGlobs: string[] }): ExcludeFacts {
  const state: ScanState = { dirs: [], dirPaths: [], ignores: [], cargoDirs: [], budget: { left: HEADER_BUDGET } };
  walk(root, "", state, false);
  rememberSubmodules(root, state);
  return {
    dirs: state.dirs, ignored: ignoredDirs(state), submodules: submoduleList(root),
    layerGlobs: policy.layerGlobs, excludeGlobs: policy.excludeGlobs, cargoDirs: state.cargoDirs,
  };
}

function ignoredDirs(state: ScanState): string[] {
  const found = state.ignores.flatMap((file) => gitignoreDirectories(file.text, file.base, state.dirPaths));
  return [...new Set(found)];
}

function rememberSubmodules(root: string, state: ScanState): void {
  for (const path of submoduleList(root)) {
    if (state.dirs.some((dir) => dir.path === path)) continue;
    state.dirs.push({ path, files: 0, generatedHeaders: 0, minified: 0, protobuf: 0, complete: true });
    state.dirPaths.push(path);
  }
}

function submoduleList(root: string): string[] {
  const listed = git(root, ["ls-files", "-s"]) ?? "";
  const links = listed.split("\n").flatMap((line) => {
    const match = /^160000 [0-9a-f]+ \d+\t(.+)$/.exec(line);
    return match === null ? [] : [match[1]!.replaceAll("\\", "/")];
  });
  return [...new Set([...links, ...gitmodulesPaths(readOptional(join(root, ".gitmodules")))])].sort(byPath);
}

function walk(root: string, rel: string, state: ScanState, read: boolean): Acc {
  const entries = listed(root, rel);
  const acc = emptyAcc();
  if (entries === null) return { ...acc, complete: false };
  entries.sort((a, b) => byPath(a.name, b.name));
  const name = nameOf(rel);
  const direct = entries.filter((entry) => entry.isFile()).length;
  const readFiles = read || readsGeneratedHeader(name) || (direct > 0 && direct <= SMALL_DIR);
  const descendRead = read || readsGeneratedHeader(name);
  for (const entry of entries) noteEntry({ root, rel, state, acc }, entry, readFiles, descendRead);
  if (rel !== "") state.dirs.push({ path: rel, ...acc });
  if (rel !== "") state.dirPaths.push(rel);
  return acc;
}

interface Visit { root: string; rel: string; state: ScanState; acc: Acc }

function noteEntry(visit: Visit, entry: Dirent, readFiles: boolean, descendRead: boolean): void {
  if (entry.isSymbolicLink()) return;
  const path = visit.rel === "" ? entry.name : `${visit.rel}/${entry.name}`;
  if (entry.isDirectory()) noteDir(visit, entry.name, path, descendRead);
  else if (entry.isFile()) noteFile(visit, entry.name, path, readFiles);
}

function noteDir(visit: Visit, name: string, path: string, descendRead: boolean): void {
  if (HEAVY.has(name) || PROTECTED.has(name) || (name === "target" && visit.state.cargoDirs.includes(visit.rel))) {
    const shallow = shallowDir(visit.root, path);
    visit.state.dirs.push(shallow);
    visit.state.dirPaths.push(path);
    add(visit.acc, shallow);
    return;
  }
  add(visit.acc, walk(visit.root, path, visit.state, descendRead));
}

function noteFile(visit: Visit, name: string, path: string, readFiles: boolean): void {
  visit.acc.files += 1;
  if (name === "Cargo.toml") visit.state.cargoDirs.push(visit.rel);
  if (name === ".gitignore") rememberIgnore(visit.root, visit.rel, path, visit.state);
  if (isMinified(name)) visit.acc.minified += 1;
  if (isProtobuf(name)) visit.acc.protobuf += 1;
  if (!readFiles) return;
  if (visit.state.budget.left <= 0) { visit.acc.complete = false; return; }
  visit.state.budget.left -= 1;
  if (generatedHeader(join(visit.root, path))) visit.acc.generatedHeaders += 1;
}

function rememberIgnore(root: string, parent: string, path: string, state: ScanState): void {
  const text = readBounded(join(root, path), IGNORE_BYTES);
  if (text !== null) state.ignores.push({ base: parent, text });
}

function shallowDir(root: string, path: string): DirFacts {
  const entries = listed(root, path);
  const files = entries === null ? 0 : entries.filter((entry) => entry.isFile() && !entry.isSymbolicLink()).length;
  return { path, files, generatedHeaders: 0, minified: 0, protobuf: 0, complete: entries !== null };
}

function listed(root: string, rel: string): Dirent[] | null {
  try { return readdirSync(join(root, rel), { withFileTypes: true }); }
  catch { return null; }
}

function generatedHeader(path: string): boolean {
  let fd: number | null = null;
  try {
    fd = openSync(path, "r");
    const buf = Buffer.alloc(HEADER_BYTES);
    const n = readSync(fd, buf, 0, HEADER_BYTES, 0);
    if (n === 0 || buf.subarray(0, n).includes(0)) return false;
    const head = buf.subarray(0, n).toString("utf8").toLowerCase().split("\n").slice(0, 12).join("\n");
    return MARKERS.some((marker) => head.includes(marker));
  } catch {
    return false;
  } finally {
    if (fd !== null) closeSync(fd);
  }
}

function readBounded(path: string, max: number): string | null {
  try {
    if (statSync(path).size > max) return null;
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function readOptional(path: string): string {
  return readBounded(path, IGNORE_BYTES) ?? "";
}

function emptyAcc(): Acc {
  return { files: 0, generatedHeaders: 0, minified: 0, protobuf: 0, complete: true };
}

function add(into: Acc, extra: Acc): void {
  into.files += extra.files;
  into.generatedHeaders += extra.generatedHeaders;
  into.minified += extra.minified;
  into.protobuf += extra.protobuf;
  into.complete &&= extra.complete;
}

function isMinified(name: string): boolean {
  return /\.min\.(js|mjs|cjs|css)$/i.test(name);
}

function isProtobuf(name: string): boolean {
  return /\.pb\.go$|_pb2\.py$|\.pb\.ts$|\.pb\.rs$/i.test(name);
}

function nameOf(path: string): string {
  const cut = path.lastIndexOf("/");
  return cut < 0 ? path : path.slice(cut + 1);
}

function byPath(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}
