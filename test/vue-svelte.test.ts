import { beforeAll, expect, test } from "bun:test";
import { grammars } from "../src/gate.ts";
import { errorIn, functions, grammarOf, imports, nestings, parse } from "../src/ts.ts";
import { markerLocations } from "../src/markers.ts";
import { compile } from "../src/compile.ts";
import { analyze } from "../src/evaluate.ts";
import { BUILTIN } from "../src/assets.ts";
import { librarySource } from "../src/library.ts";
import { VERSIONS } from "../src/gate.ts";

beforeAll(grammars);

test("Vue SFC with generic setup script, companion script and template directives parses with exact line numbers", () => {
  const source = [
    "<template>",
    '  <!-- @generated by UI builder -->',
    '  <div v-if="count < 10 && ready" @click="increment()">{{ count }}</div>',
    "</template>",
    '<script lang="ts">',
    'import type { PropType } from "vue";',
    "export const COMPONENT_NAME = 'Counter';",
    "</script>",
    '<script setup lang="ts" generic="T extends Array<string>">',
    'import { ref } from "vue";',
    "function compute(a: number, b: number, c: number, d: number, e: number) {",
    "  if (a > 0) {",
    "    if (b > 0) {",
    "      return a + b + c + d + e;",
    "    }",
    "  }",
    "  return 0;",
    "}",
    "const count = ref(0);",
    "</script>",
    "<style scoped>",
    ".counter > span { color: red; }",
    "</style>",
    "",
  ].join("\n");

  expect(grammarOf("src/components/Counter.vue")).toBe("tsx");
  const parsed = parse("src/components/Counter.vue", source);
  expect(errorIn(parsed, null)).toBeNull();
  expect(imports(parsed)).toEqual([
    { spec: "vue", line: 6, kind: "type", literal: true },
    { spec: "vue", line: 10, kind: "static", literal: true },
  ]);
  expect(functions(parsed)).toEqual([
    { symbol: "compute", line: 11, lines: 8, params: 5 },
  ]);
  expect(nestings(parsed)).toEqual([
    { symbol: "compute", line: 12, measured: 1, own: null },
    { symbol: "compute", line: 13, measured: 2, own: null },
  ]);
  const markers = markerLocations("src/components/Counter.vue", source, ["@generated"], parsed, ["@generated"]);
  expect(markers).toEqual([{ line: 2, key: "@generated\0/*   @generated by UI builder  */" }]);
  parsed.root.tree.delete();
});

test("Svelte component with module and instance scripts evaluates TypeScript and Vue/clean-code rules on script lines", () => {
  const svelteSource = [
    '<script context="module" lang="ts">',
    '  import { writable } from "svelte/store";',
    "  export const shared = writable(0);",
    "</script>",
    '<script lang="ts">',
    "  export let count = 0;",
    "  const bad: any = count;",
    "</script>",
    "{#if count > 0}",
    "  <button on:click={() => count += 1}>{count}</button>",
    "{/if}",
    "",
  ].join("\n");

  expect(grammarOf("src/Counter.svelte")).toBe("tsx");
  const preset = JSON.stringify({
    name: "vue-svelte-test",
    version: "0.0.1",
    engine: VERSIONS.engine,
    sources: [
      { ns: "core", kind: "builtin", version: VERSIONS.core },
      { ns: "typescript", kind: "library", version: "1.2.0" },
      { ns: "vue", kind: "library", version: "1.2.0" },
    ],
    methodologies: ["core/pregate-integrity", "typescript/strict-types", "typescript/anti-evasion", "vue/reactivity"],
    overrides: { "TS-ANY-001": { severity: "deny" } },
  });
  const compiled = compile(preset, (s) => (s.kind === "builtin" ? BUILTIN : librarySource(s.ns)), VERSIONS);
  expect("lock" in compiled, "errors" in compiled ? compiled.errors.join("\n") : "").toBe(true);
  if (!("lock" in compiled)) return;

  const svelteResult = analyze(compiled.lock, "pre", "src/Counter.svelte", svelteSource, {
    read: () => null,
    now: () => 0,
  });
  expect("violations" in svelteResult).toBe(true);
  if ("violations" in svelteResult) {
    expect(svelteResult.violations).toContainEqual(
      expect.objectContaining({ path: "src/Counter.svelte", line: 7 }),
    );
  }

  const vueSource = [
    "<template><p>{{ title }}</p></template>",
    '<script setup lang="ts">',
    'import { ref } from "vue";',
    "const title = ref(null);",
    "</script>",
    "",
  ].join("\n");
  const vueResult = analyze(compiled.lock, "pre", "src/Title.vue", vueSource, {
    read: () => null,
    now: () => 0,
  });
  expect("violations" in vueResult).toBe(true);
  if ("violations" in vueResult) {
    expect(vueResult.violations).toContainEqual(
      expect.objectContaining({ rule: "vue/VUE-REF-001", path: "src/Title.vue", line: 4 }),
    );
  }
});
